/** One cell, by the three coordinates that name it. */
export const cell = (wiring: WiringName, condition: Condition, probe: ProbeName): string =>
  MATRIX[wiring][condition][probe]

/** The probes on which two wirings disagree, under one condition. */
export function differences(
  left: WiringName,
  right: WiringName,
  condition: Condition,
): readonly ProbeName[] {
  return PROBE_NAMES.filter((probe) => cell(left, condition, probe) !== cell(right, condition, probe))
}

/** The wirings whose answer to a probe is one of the given words. */
export function wiringsAnswering(
  condition: Condition,
  probe: ProbeName,
  ...outcomes: readonly string[]
): readonly WiringName[] {
  return WIRING_NAMES.filter((wiring) => outcomes.includes(cell(wiring, condition, probe)))
}

/**
 * Cells the probe's own vocabulary does not allow.
 *
 * The table is a nested record of strings, and TypeScript is content with any
 * string in any cell. This is the check that is not — a cell holding
 * `'stalee'` is a typo the compiler cannot see and this function can.
 */
export function invalidCells(): readonly string[] {
  const problems: string[] = []

  for (const wiring of WIRING_NAMES) {
    for (const condition of CONDITIONS) {
      for (const probe of PROBE_NAMES) {
        const outcomes = probeByName(probe)?.outcomes ?? []
        const value = cell(wiring, condition, probe)

        if (!outcomes.includes(value)) {
          problems.push(
            `${wiring}/${condition}/${probe} is ${JSON.stringify(value)}, which is not one of ` +
              outcomes.map((outcome) => JSON.stringify(outcome)).join(', '),
          )
        }
      }
    }
  }

  return problems
}

/**
 * Render one condition's half of the table as Markdown.
 *
 * `README.md` holds the output of this function verbatim, and `readme.test.ts`
 * re-renders it and asserts the file still contains it. That is a stronger
 * guarantee than the usual "the README mentions the number": the published
 * table cannot disagree with the data in any cell, in any row order, or by a
 * column somebody added and forgot to document — the two are the same string
 * or the build is red.
 *
 * Probes are rows and wirings are columns, which is the transpose of how the
 * data is stored. Eight columns fit a page and twelve do not, and the reading
 * people do here is down a column: "what does this wiring cost me".
 */
export function renderTable(condition: Condition): string {
  const header = `| probe | ${WIRING_NAMES.join(' | ')} |`
  const rule = `| --- | ${WIRING_NAMES.map(() => '---').join(' | ')} |`
  const rows = PROBE_NAMES.map(
    (probe) => `| \`${probe}\` | ${WIRING_NAMES.map((wiring) => cell(wiring, condition, probe)).join(' | ')} |`,
  )

  return [header, rule, ...rows].join('\n')
}

/**
 * A claim the README makes, stated as a question to the table.
 *
 * `holds` returns the empty string when the claim is true and an explanation
 * when it is not, so a failing finding says what the table actually contains
 * rather than `expected true to be false`.
 */
export interface Finding {
  readonly id: string
  /** The claim, in the words the README uses. */
  readonly claim: string
  readonly holds: () => string
}

const listEquals = (actual: readonly string[], expected: readonly string[]): string => {
  const left = [...actual].sort().join(', ')
  const right = [...expected].sort().join(', ')

  return left === right ? '' : `got [${left}], expected [${right}]`
}

