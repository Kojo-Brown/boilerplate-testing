/**
 * The measurement: eight wirings, two conditions, twelve probes.
 *
 * ---------------------------------------------------------------------------
 * What the table is, and what it is not
 * ---------------------------------------------------------------------------
 * Every cell below is a *claim about Chromium*, and `fidelity.spec.ts` checks
 * all 192 of them against a real browser on every run. Nothing here is derived
 * from a changelog, from Playwright's documentation, or from what the author
 * expected — several cells are the opposite of the first draft, and the
 * findings at the bottom of this file are the reason the draft was wrong.
 *
 * Writing the table down rather than generating it from the run is deliberate,
 * and it is the same choice `ct/README.md` makes about jsdom: a matrix
 * generated by the measurement agrees with the measurement by construction and
 * can never fail. This one can, and when it does, one of two things is true —
 * Playwright changed, or somebody changed a wiring without noticing what it
 * cost. Both are worth a red build.
 *
 * ---------------------------------------------------------------------------
 * The findings are derived, not declared
 * ---------------------------------------------------------------------------
 * {@link FINDINGS} holds the claims this directory's README makes in prose.
 * Each one is a function over the table rather than a sentence, so the README
 * cannot drift from the measurement: change a cell and the finding that
 * depended on it fails in `matrix.test.ts`, before anybody reads the paragraph
 * it contradicts.
 */

